"""
Personal RAG knowledge base.
Stores and retrieves your trading knowledge for AI agents.
"""

from typing import List, Optional, Dict
from datetime import datetime
from sqlalchemy.orm import Session
from sqlalchemy import and_, or_

from core.models import KnowledgeEntry
import logging

logger = logging.getLogger(__name__)


class KnowledgeBase:
    """
    Manages personal trading knowledge entries.
    Each entry is a piece of knowledge that agents can retrieve.

    Knowledge types:
    - strategy: Strategy-related knowledge
    - lesson: Lessons learned from trades
    - pattern: Behavioral or market patterns discovered
    - insight: AI-generated insights worth remembering
    - rule: Personal trading rules
    - review: Weekly/monthly review summaries
    """

    def __init__(self, db: Session):
        self.db = db

    def add_entry(
        self,
        category: str,
        title: str,
        content: str,
        source: str = "manual",
        tags: Optional[List[str]] = None,
    ) -> KnowledgeEntry:
        """Add a new knowledge entry."""
        entry = KnowledgeEntry(
            category=category,
            title=title,
            content=content,
            source=source,
            tags=tags or [],
        )
        self.db.add(entry)
        self.db.flush()
        logger.info(f"Knowledge entry added: [{category}] {title}")
        return entry

    def add_lesson_from_trade(
        self,
        trade_id: str,
        lesson: str,
        strategy_name: Optional[str] = None,
    ) -> KnowledgeEntry:
        """Add a lesson learned from a specific trade."""
        tags = ["trade_lesson"]
        if strategy_name:
            tags.append(f"strategy:{strategy_name}")

        return self.add_entry(
            category="lesson",
            title=f"Trade Lesson: {lesson[:80]}",
            content=f"Trade ID: {trade_id}\nStrategy: {strategy_name or 'N/A'}\n\nLesson: {lesson}",
            source="trade_analysis",
            tags=tags,
        )

    def add_insight(
        self,
        title: str,
        content: str,
        agent_name: str,
        tags: Optional[List[str]] = None,
    ) -> KnowledgeEntry:
        """Add an AI-generated insight."""
        return self.add_entry(
            category="insight",
            title=title,
            content=f"Generated by: {agent_name}\n\n{content}",
            source=f"ai_{agent_name}",
            tags=tags or ["ai_generated"],
        )

    def add_rule(
        self,
        rule: str,
        context: Optional[str] = None,
    ) -> KnowledgeEntry:
        """Add a personal trading rule."""
        content = f"RULE: {rule}"
        if context:
            content += f"\n\nContext: {context}"
        return self.add_entry(
            category="rule",
            title=f"Rule: {rule[:80]}",
            content=content,
            source="manual",
            tags=["personal_rule"],
        )

    def search(
        self,
        query: str,
        category: Optional[str] = None,
        limit: int = 10,
    ) -> List[KnowledgeEntry]:
        """Simple keyword search in knowledge base."""
        q = self.db.query(KnowledgeEntry)

        if category:
            q = q.filter(KnowledgeEntry.category == category)

        # Simple text search
        search_term = f"%{query}%"
        q = q.filter(
            or_(
                KnowledgeEntry.title.ilike(search_term),
                KnowledgeEntry.content.ilike(search_term),
            )
        )

        entries = q.order_by(KnowledgeEntry.created_at.desc()).limit(limit).all()

        # Update relevance count
        for entry in entries:
            entry.relevance_count = (entry.relevance_count or 0) + 1
            entry.last_referenced = datetime.now()

        self.db.flush()
        return entries

    def get_by_category(
        self,
        category: str,
        limit: int = 20,
    ) -> List[KnowledgeEntry]:
        """Get entries by category."""
        return self.db.query(KnowledgeEntry).filter(
            KnowledgeEntry.category == category
        ).order_by(KnowledgeEntry.created_at.desc()).limit(limit).all()

    def get_strategy_knowledge(
        self,
        strategy_name: str,
        limit: int = 10,
    ) -> List[KnowledgeEntry]:
        """Get all knowledge related to a specific strategy."""
        return self.db.query(KnowledgeEntry).filter(
            KnowledgeEntry.tags.contains([f"strategy:{strategy_name}"])
        ).order_by(KnowledgeEntry.created_at.desc()).limit(limit).all()

    def get_recent_lessons(self, limit: int = 10) -> List[KnowledgeEntry]:
        """Get most recent lessons."""
        return self.db.query(KnowledgeEntry).filter(
            KnowledgeEntry.category == "lesson"
        ).order_by(KnowledgeEntry.created_at.desc()).limit(limit).all()

    def get_context_for_agent(
        self,
        strategy_name: Optional[str] = None,
        query: Optional[str] = None,
        max_entries: int = 5,
    ) -> str:
        """
        Build context string from knowledge base for agent consumption.
        """
        entries = []

        if strategy_name:
            entries.extend(self.get_strategy_knowledge(strategy_name, limit=3))

        if query:
            entries.extend(self.search(query, limit=3))

        # Always include recent lessons
        recent = self.get_recent_lessons(limit=2)
        entries.extend(recent)

        # Deduplicate
        seen_ids = set()
        unique = []
        for e in entries:
            if e.id not in seen_ids:
                seen_ids.add(e.id)
                unique.append(e)

        # Format for agent
        if not unique:
            return "No relevant knowledge entries found."

        parts = ["PERSONAL KNOWLEDGE BASE:"]
        for entry in unique[:max_entries]:
            parts.append(f"\n[{entry.category.upper()}] {entry.title}")
            parts.append(entry.content[:300])

        return "\n".join(parts)