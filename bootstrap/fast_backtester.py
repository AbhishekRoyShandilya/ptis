# bootstrap/fast_backtester.py
"""
Fast Backtest Engine
=====================

Creates SYNTHETIC trade history from historical market data
using the draft strategy rules.

Purpose:
- Warm-start all systems (scaler, clusterer, regime checker)
- Give AVT initial data to work with
- Validate that our rules produce reasonable results
- Compare synthetic performance with user's claimed performance
- Initialize feature distributions

This is NOT a full backtester. It's a BOOTSTRAPPER.
Speed > precision. We need approximate results fast.
Results are tagged as "synthetic" and weighted lower
than real trades.

Key principle: CONSERVATIVE.
If unsure about a signal, SKIP IT.
Better to miss signals than generate false ones.
Synthetic history should UNDERPERFORM reality
(because we're missing the judgment layer).

DOMAIN SEPARATION: This backtester is INFORMATIONAL ONLY.
Its output (WR, Avg R, trades) goes to warm-start and AVT,
NOT into StrategyProfile. Onboarding NEVER rejects a strategy
based on backtest outcomes. It only informs the user.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from typing import Any, Dict, List, Optional, Tuple

import numpy as np

logger = logging.getLogger(__name__)


@dataclass
class SyntheticTrade:
    """A trade generated by the fast backtester."""
    id: str = ""
    symbol: str = ""
    direction: str = "long"

    entry_time: Optional[datetime] = None
    entry_price: float = 0.0
    exit_time: Optional[datetime] = None
    exit_price: float = 0.0
    stop_price: float = 0.0

    pnl: float = 0.0
    r_multiple: float = 0.0
    max_favorable_r: float = 0.0
    max_adverse_r: float = 0.0

    # Features captured at entry
    features_at_entry: Dict[str, float] = field(
        default_factory=dict
    )
    features_at_peak: Dict[str, float] = field(
        default_factory=dict
    )

    # Raw candle window at entry (context + entry bar) — retained so the
    # SKO compiler can run SKE's FeatureComputer on real candles, keeping
    # scoring_config feature names aligned with AVT's runtime features.
    entry_candles: List[Dict[str, Any]] = field(default_factory=list)

    # Context
    market_regime: str = ""
    conviction_score: float = 0.0
    variant_id: Optional[str] = None

    # Metadata
    is_synthetic: bool = True
    synthetic_confidence: float = 0.0
    # How confident we are this trade would have been
    # taken by the real strategy (0-1)
    # Lower for judgment-heavy strategies

    exit_reason: str = ""


@dataclass
class BacktestResult:
    """Result of fast backtest."""
    trades: List[SyntheticTrade] = field(default_factory=list)

    # Performance
    total_trades: int = 0
    win_rate: float = 0.0
    avg_r: float = 0.0
    total_r: float = 0.0
    profit_factor: float = 0.0
    max_drawdown_r: float = 0.0

    # Feature data for warm-starting
    feature_vectors: List[Dict[str, float]] = field(
        default_factory=list
    )
    regime_distribution: Dict[str, int] = field(
        default_factory=dict
    )

    # Validation
    matches_user_claim: bool = False
    user_claimed_wr: Optional[float] = None
    synthetic_wr: float = 0.0
    deviation_from_claim: float = 0.0

    # Quality
    avg_synthetic_confidence: float = 0.0
    warnings: List[str] = field(default_factory=list)

    # Period
    start_date: Optional[datetime] = None
    end_date: Optional[datetime] = None
    symbols_tested: int = 0


class FastBacktestEngine:
    """
    Runs fast backtests to generate synthetic history.

    NOT a full-featured backtester. Designed for:
    - Speed (seconds, not minutes)
    - Bootstrapping (warm-start, not analysis)
    - Conservative (skip uncertain signals)

    Uses pre-computed feature data from market_data service.
    """

    def __init__(
        self,
        market_data: Any,            # market data service
        feature_computer: Any,       # feature computation service
        regime_engine: Any,          # regime classification service
    ):
        self._market = market_data
        self._features = feature_computer
        self._regime = regime_engine

    async def run(
        self,
        draft: Any,                  # StrategyDraft
        symbols: List[str],
        lookback_days: int = 180,
        max_trades: int = 200,
    ) -> BacktestResult:
        """
        Run fast backtest over historical data.

        Strategy:
        1. For each day in lookback:
           For each symbol:
             Compute features at each candle
             Check hard rules
             If passed: compute soft score
             If soft score > conservative threshold: simulate trade
        2. Collect all synthetic trades
        3. Compute statistics
        4. Compare with user's claims
        """
        result = BacktestResult()
        result.start_date = datetime.now(timezone.utc) - timedelta(
            days=lookback_days
        )
        result.end_date = datetime.now(timezone.utc)
        result.symbols_tested = len(symbols)

        trades = []
        feature_vectors = []

        # Conservative soft score threshold
        # We DELIBERATELY set this high to avoid false signals
        # Better to miss than to generate garbage synthetic history
        min_soft_score = 0.60

        # Build hard rule checker
        hard_rules = draft.hard_rules
        soft_scorers = draft.soft_scorers

        for symbol in symbols:
            try:
                symbol_trades = await self._backtest_symbol(
                    symbol=symbol,
                    hard_rules=hard_rules,
                    soft_scorers=soft_scorers,
                    exit_logic=draft.exit_logic,
                    lookback_days=lookback_days,
                    min_soft_score=min_soft_score,
                    draft=draft,
                )

                trades.extend(symbol_trades)
                for t in symbol_trades:
                    if t.features_at_entry:
                        feature_vectors.append(t.features_at_entry)

                if len(trades) >= max_trades:
                    break

            except Exception as e:
                logger.warning(
                    "Backtest failed for %s: %s", symbol, e
                )
                continue

        # Compute results
        result.trades = trades[:max_trades]
        result.total_trades = len(result.trades)
        result.feature_vectors = feature_vectors

        if result.trades:
            r_values = [t.r_multiple for t in result.trades]
            wins = [r for r in r_values if r > 0]
            losses = [r for r in r_values if r <= 0]

            result.win_rate = len(wins) / len(r_values)
            result.avg_r = float(np.mean(r_values))
            result.total_r = float(np.sum(r_values))
            result.synthetic_wr = result.win_rate

            if losses:
                result.profit_factor = (
                    abs(sum(wins)) / abs(sum(losses))
                    if sum(losses) != 0
                    else float("inf")
                )

            # Max drawdown
            cumulative = np.cumsum(r_values)
            peak = np.maximum.accumulate(cumulative)
            drawdown = peak - cumulative
            result.max_drawdown_r = float(np.max(drawdown))

            # Regime distribution
            for t in result.trades:
                regime = t.market_regime or "unknown"
                result.regime_distribution[regime] = (
                    result.regime_distribution.get(regime, 0) + 1
                )

            # Average synthetic confidence
            result.avg_synthetic_confidence = float(np.mean(
                [t.synthetic_confidence for t in result.trades]
            ))

        # Warnings
        if result.total_trades < 30:
            result.warnings.append(
                f"Only {result.total_trades} synthetic trades "
                f"generated. Need more for reliable warm-start."
            )

        if result.avg_synthetic_confidence < 0.5:
            result.warnings.append(
                "Low average confidence in synthetic trades. "
                "Strategy may be too judgment-heavy for reliable "
                "backtesting. Use with caution."
            )

        return result

    async def _backtest_symbol(
        self,
        symbol: str,
        hard_rules: List[Dict],
        soft_scorers: List[Dict],
        exit_logic: List[Dict],
        lookback_days: int,
        min_soft_score: float,
        draft: Any,
    ) -> List[SyntheticTrade]:
        """Backtest a single symbol."""
        trades = []

        # Get historical candles
        candles = await self._market.get_historical_candles(
            symbol=symbol,
            timeframe=draft.timeframe or "5min",
            lookback_days=lookback_days,
        )

        if not candles or len(candles) < 50:
            return trades

        in_trade = False
        current_trade = None

        for i in range(50, len(candles)):
            candle = candles[i]
            context = candles[max(0, i - 50):i]

            if in_trade and current_trade:
                # Check exit
                exit_result = self._check_exit(
                    current_trade, candle, context, exit_logic
                )
                if exit_result["should_exit"]:
                    current_trade = self._close_trade(
                        current_trade, candle, exit_result
                    )
                    trades.append(current_trade)
                    in_trade = False
                    current_trade = None
                else:
                    # Update MFE/MAE
                    self._update_excursion(current_trade, candle)
                continue

            # Check entry
            try:
                features = await self._features.compute_from_candles(
                    symbol, context, candle
                )
            except Exception:
                continue

            if not features:
                continue

            # Hard rules
            hard_pass = self._check_hard_rules(features, hard_rules)
            if not hard_pass:
                continue

            # Soft score
            soft_score = self._compute_soft_score(
                features, soft_scorers
            )
            if soft_score < min_soft_score:
                continue

            # Regime
            try:
                regime = await self._regime.classify_from_candles(
                    context
                )
            except Exception:
                regime = "unknown"

            # Compute synthetic confidence
            # Higher for quantifiable rules, lower for judgment-heavy
            quantifiable_ratio = sum(
                1 for r in hard_rules
                if r.get("source") == "user_extracted"
            ) / max(1, len(hard_rules))

            synthetic_confidence = (
                soft_score * 0.4
                + quantifiable_ratio * 0.3
                + (draft.understanding_confidence or 0.5) * 0.3
            )

            # Create trade
            stop_price = self._compute_stop(
                candle, context, exit_logic, features
            )
            risk = abs(candle["close"] - stop_price)
            if risk <= 0:
                continue

            current_trade = SyntheticTrade(
                id=f"syn_{symbol}_{i}",
                symbol=symbol,
                direction="long",
                entry_time=candle.get("timestamp"),
                entry_price=candle["close"],
                stop_price=stop_price,
                features_at_entry=features,
                entry_candles=list(context) + [candle],
                market_regime=str(regime),
                conviction_score=soft_score,
                synthetic_confidence=round(
                    synthetic_confidence, 3
                ),
            )
            in_trade = True

        # Close any remaining trade
        if in_trade and current_trade and candles:
            last = candles[-1]
            current_trade = self._close_trade(
                current_trade, last,
                {"reason": "end_of_data", "exit_price": last["close"]},
            )
            trades.append(current_trade)

        return trades

    def _check_hard_rules(
        self,
        features: Dict[str, float],
        rules: List[Dict],
    ) -> bool:
        """Check all hard rules. ALL must pass."""
        for rule in rules:
            field_name = rule.get("field", "")
            operator = rule.get("operator", "gte")
            threshold = rule.get("value")

            if threshold is None:
                continue

            actual = features.get(field_name)
            if actual is None:
                return False  # missing data = fail

            try:
                actual = float(actual)
                threshold_f = float(threshold) if not isinstance(
                    threshold, (list, tuple)
                ) else threshold
            except (ValueError, TypeError):
                return False

            if operator == "gte" and actual < threshold_f:
                return False
            elif operator == "gt" and actual <= threshold_f:
                return False
            elif operator == "lte" and actual > threshold_f:
                return False
            elif operator == "lt" and actual >= threshold_f:
                return False
            elif operator == "eq" and abs(actual - threshold_f) > 0.01:
                return False
            elif operator == "between":
                if isinstance(threshold, (list, tuple)) and len(threshold) == 2:
                    if actual < threshold[0] or actual > threshold[1]:
                        return False

        return True

    def _compute_soft_score(
        self,
        features: Dict[str, float],
        scorers: List[Dict],
    ) -> float:
        """
        Compute soft score. Since we don't have actual
        scoring functions yet (they depend on market data
        that may not be in features), we approximate
        using feature ranges.
        """
        if not scorers:
            return 0.5

        # Simple: check if features are in expected ranges
        # This is a rough approximation
        scores = []
        for scorer in scorers:
            name = scorer.get("name", "")
            weight = scorer.get("weight", 1.0)

            # Check if any feature roughly maps to this scorer
            # This is intentionally conservative
            score = 0.5  # neutral default
            scores.append(score * weight)

        total_weight = sum(s.get("weight", 1.0) for s in scorers)
        if total_weight == 0:
            return 0.5

        return sum(scores) / total_weight

    def _compute_stop(
        self,
        candle: Dict,
        context: List[Dict],
        exit_logic: List[Dict],
        features: Dict[str, float],
    ) -> float:
        """Compute stop loss price."""
        # Look for ATR-based stop in exit logic
        for exit_rule in exit_logic:
            if "atr" in str(exit_rule).lower():
                atr = features.get("atr", 0)
                multiplier = exit_rule.get("params", {}).get(
                    "atr_multiple", 1.5
                )
                if atr > 0:
                    return candle["close"] - (atr * multiplier)

        # Default: use recent low or 2% below
        recent_lows = [c.get("low", 0) for c in context[-10:]]
        if recent_lows:
            return min(recent_lows) * 0.998

        return candle["close"] * 0.98

    def _check_exit(
        self,
        trade: SyntheticTrade,
        candle: Dict,
        context: List[Dict],
        exit_logic: List[Dict],
    ) -> Dict[str, Any]:
        """Check if trade should be exited."""
        price = candle.get("low", candle.get("close", 0))

        # Stop loss
        if price <= trade.stop_price:
            return {
                "should_exit": True,
                "reason": "stop_loss",
                "exit_price": trade.stop_price,
            }

        # Time exit (if configured)
        for rule in exit_logic:
            if rule.get("type") == "time_exit":
                max_candles = rule.get("params", {}).get(
                    "max_candles", 20
                )
                # Approximate: if we've been in trade for many candles
                if (
                    trade.entry_time
                    and candle.get("timestamp")
                    and hasattr(trade.entry_time, "__sub__")
                ):
                    # Simplified time check
                    pass

        # Simple target: 3R
        if trade.entry_price > 0 and trade.stop_price > 0:
            risk = trade.entry_price - trade.stop_price
            if risk > 0:
                current_r = (
                    candle.get("high", candle["close"])
                    - trade.entry_price
                ) / risk
                if current_r >= 3.0:
                    return {
                        "should_exit": True,
                        "reason": "target_3r",
                        "exit_price": trade.entry_price + risk * 3,
                    }

        return {"should_exit": False}

    def _close_trade(
        self,
        trade: SyntheticTrade,
        candle: Dict,
        exit_result: Dict,
    ) -> SyntheticTrade:
        """Close a trade with exit info."""
        trade.exit_time = candle.get("timestamp")
        trade.exit_price = exit_result.get(
            "exit_price", candle["close"]
        )
        trade.exit_reason = exit_result.get("reason", "unknown")

        risk = abs(trade.entry_price - trade.stop_price)
        if risk > 0:
            trade.r_multiple = round(
                (trade.exit_price - trade.entry_price) / risk, 2
            )
        trade.pnl = trade.exit_price - trade.entry_price

        return trade

    def _update_excursion(
        self, trade: SyntheticTrade, candle: Dict
    ) -> None:
        """Update max favorable/adverse excursion."""
        risk = abs(trade.entry_price - trade.stop_price)
        if risk <= 0:
            return

        high = candle.get("high", candle.get("close", 0))
        low = candle.get("low", candle.get("close", 0))

        favorable_r = (high - trade.entry_price) / risk
        adverse_r = (trade.entry_price - low) / risk

        trade.max_favorable_r = max(
            trade.max_favorable_r, favorable_r
        )
        trade.max_adverse_r = max(trade.max_adverse_r, adverse_r)